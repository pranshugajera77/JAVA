// print a table with loop.....

public class print_table {
    
    public static void main(String[] args) {
        
        int n = 5;

        // Nested For loop.....

        for (n = 5; n <=5; n++){
            for (int i=1;i<11;i++) {
            System.out.println("5"+" * "+ i +" " +"= "+ n*i);
            }
        }
    }

}
